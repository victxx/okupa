# Writes web/src/font.js from the console's own title font (game/src/font_sans.c, bold).
# Run from the repo root: python3 web/scripts/font.py
import re

s = open('game/src/font_sans.c').read()
adv = [int(x) for x in re.search(r'bold_adv\[95\] = \{([^}]*)\}', s).group(1).split(',')]
body = s[s.index('bold_rows[95][13] = {'):s.index('const ok_font_sans ok_sans_bold')]
rows = [[int(v, 16) for v in m.split(',')] for m in re.findall(r'\{(0x[0-9a-fx, ]*)\}', body)]
assert len(rows) == 95 and all(len(r) == 13 for r in rows), len(rows)

JS = """// Pixel Operator Bold by Jayvee Enaguas (HarvettFox96), CC0 1.0: the same glyphs as the
// console's title (game/src/font_sans.c, ok_sans_bold), printable ASCII, 13 rows, bit 0 = left.
// Generated by web/scripts/font.py; do not edit by hand.
export const ADV = @ADV@;
export const ROWS = @ROWS@;

// Draws text at an integer scale. The shadow (optional) is offset, and dotted on request like the
// console's intro title.
export function pixelText(canvas, text, { scale = 4, ink = '#2b2a28', shadow = null, off = 1, pad = 1, dotted = false } = {}) {
  const glyphs = [...text].map((ch) => ch.charCodeAt(0) - 32).filter((i) => i >= 0 && i < 95);
  const w = glyphs.reduce((a, i) => a + ADV[i], 0) + off + pad * 2, h = 13 + off + pad * 2;
  canvas.width = w * scale; canvas.height = h * scale;
  const g = canvas.getContext('2d');
  const stamp = (dx, dy, color, dotted) => {
    g.fillStyle = color;
    let x0 = pad + dx;
    for (const i of glyphs) {
      for (let y = 0; y < 13; y++) for (let x = 0; x < 16; x++) {
        if (!((ROWS[i][y] >> x) & 1)) continue;
        if (dotted && (x0 + x + y) % 2) continue;
        g.fillRect((x0 + x) * scale, (pad + dy + y) * scale, scale, scale);
      }
      x0 += ADV[i];
    }
  };
  if (shadow) stamp(off, off, shadow, dotted);
  stamp(0, 0, ink, false);
  canvas.style.aspectRatio = `${w} / ${h}`;
}
"""
out = JS.replace('@ADV@', str(adv)).replace('@ROWS@', '[\n  ' + ',\n  '.join(str(r) for r in rows) + '\n]')
open('web/src/font.js', 'w').write(out)
print('web/src/font.js', len(rows), 'glyphs')
