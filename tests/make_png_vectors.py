"""Writes tests/png_vectors.h: small PNGs made with Python's zlib (stored,
fixed and dynamic deflate blocks), every scanline filter, grey, RGB and RGBA,
with the DS colours each pixel must decode to. Run: python3 -I tests/make_png_vectors.py"""
import struct, zlib, random

def chunk(t, d):
    return struct.pack(">I", len(d)) + t + d + struct.pack(">I", zlib.crc32(t + d) & 0xffffffff)

def paeth(a, b, c):
    p = a + b - c; pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
    return a if pa <= pb and pa <= pc else b if pb <= pc else c

def png(w, h, ch, pixels, strategy, level):
    ct = {1: 0, 3: 2, 4: 6}[ch]
    raw, prev = b"", bytes(w * ch)
    for y in range(h):
        row = bytes(pixels[(y * w) * ch:(y * w + w) * ch]); f = y % 5; out = bytearray([f])
        for x in range(w * ch):
            a = row[x - ch] if x >= ch else 0; b = prev[x]; c = prev[x - ch] if x >= ch else 0
            v = [0, a, b, (a + b) // 2, paeth(a, b, c)][f]
            out.append((row[x] - v) & 255)
        raw += bytes(out); prev = row
    co = zlib.compressobj(level, zlib.DEFLATED, 15, 9, strategy)
    z = co.compress(raw) + co.flush()
    return b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", w, h, 8, ct, 0, 0, 0)) + \
        chunk(b"tEXt", b"Comment\x00okupa test") + chunk(b"IDAT", z[:len(z) // 2]) + chunk(b"IDAT", z[len(z) // 2:]) + \
        chunk(b"IEND", b"")

def ds(r, g, b):
    return 0x8000 | (r >> 3) | (g >> 3) << 5 | (b >> 3) << 10

random.seed(7)
cases = []
for name, ch, strategy, level in [("rgb_dynamic", 3, zlib.Z_DEFAULT_STRATEGY, 9), ("rgb_fixed", 3, zlib.Z_FIXED, 6),
                                  ("rgba_stored", 4, zlib.Z_DEFAULT_STRATEGY, 0), ("grey_dynamic", 1, zlib.Z_DEFAULT_STRATEGY, 9)]:
    w, h = 17, 11
    px = [(x * 13 + y * 7 + random.randrange(4)) & 255 for y in range(h) for x in range(w * ch)]
    data = png(w, h, ch, px, strategy, level)
    expect = []
    for i in range(w * h):
        p = px[i * ch:i * ch + ch]
        expect.append(ds(p[0], p[0], p[0]) if ch == 1 else ds(p[0], p[1], p[2]))
    cases.append((name, w, h, data, expect))

with open("tests/png_vectors.h", "w") as f:
    f.write("/* Generated by tests/make_png_vectors.py (Python zlib); do not edit. */\n")
    for name, w, h, data, expect in cases:
        f.write("static const unsigned char %s_png[%d] = {%s};\n" % (name, len(data), ",".join(str(b) for b in data)))
        f.write("static const unsigned short %s_px[%d] = {%s};\n" % (name, len(expect), ",".join(str(v) for v in expect)))
    f.write("static const struct { const char *name; const unsigned char *png; unsigned n; int w, h; const unsigned short *px; } png_cases[] = {\n")
    for name, w, h, data, expect in cases:
        f.write('    {"%s", %s_png, %d, %d, %d, %s_px},\n' % (name, name, len(data), w, h, name))
    f.write("};\n")
print("wrote", len(cases), "cases")
