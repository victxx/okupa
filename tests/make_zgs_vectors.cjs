// Writes tests/zgs_vectors.h with the official 0G Storage SDK (1.2.13, from
// tools/zerog-store): file roots, submission nodes and submit() calldata for
// files of several sizes. Run: node tests/make_zgs_vectors.cjs
const path = require("path");
const nm = path.join(__dirname, "../tools/zerog-store/node_modules");
const { MemData } = require(nm + "/@0gfoundation/0g-storage-ts-sdk");
const { ethers } = require(nm + "/ethers");
const fs = require("fs");
const submitter = "0x8000feB052Cf38E5BA9254f1D9D7e40B5098352d";
const iface = new ethers.Interface(["function submit(((uint256 length, bytes tags, (bytes32 root, uint256 height)[] nodes) data, address submitter) submission) payable returns (uint256, bytes32, uint256, uint256)"]);
(async () => {
  const sizes = [1, 255, 256, 257, 5000, 37 * 256, 100000, 262143, 262144];
  let out = "/* Generated by tests/make_zgs_vectors.cjs with the 0G Storage SDK 1.2.13; do not edit.\n * Data byte i is (i * 31 + 7) & 255. */\n";
  out += "static const struct { unsigned size; const char *root; int nodes; int height[12]; const char *node_root[12]; const char *calldata; } zgs_cases[] = {\n";
  for (const size of sizes) {
    const data = new Uint8Array(size);
    for (let i = 0; i < size; i++) data[i] = (i * 31 + 7) & 255;
    const f = new MemData(data);
    const [tree, err] = await f.merkleTree();
    if (err) throw err;
    const [sub, err2] = await f.createSubmission("0x", submitter);
    if (err2) throw err2;
    const call = iface.encodeFunctionData("submit", [sub]);
    const h = sub.data.nodes.map(n => Number(n.height)), r = sub.data.nodes.map(n => '"' + n.root.slice(2) + '"');
    while (h.length < 12) { h.push(0); r.push("0"); }
    out += `    {${size}, "${tree.rootHash().slice(2)}", ${sub.data.nodes.length}, {${h.join(",")}}, {${r.join(",")}},\n     "${call.slice(2)}"},\n`;
  }
  out += "};\n";
  fs.writeFileSync(path.join(__dirname, "zgs_vectors.h"), out);
  console.log("wrote", sizes.length, "cases");
})().catch(e => { console.error(e); process.exit(1); });
