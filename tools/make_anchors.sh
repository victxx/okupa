#!/bin/sh
# Regenerates core/src/tls_anchors.c from the root certificates in tools/roots
# (exported from the macOS system keychain; fingerprints in THIRD_PARTY.md),
# using BearSSL's own brssl tool built from the pinned submodule.
set -eu
cd "$(dirname "$0")/.."
B=third_party/bearssl
tmp=$(mktemp -d)
cc -O1 -w -I$B/inc -I$B/src -I$B/tools $(find $B/src -name '*.c') $B/tools/*.c -o "$tmp/brssl"
cat tools/roots/*.pem > "$tmp/roots.pem"
{
    echo "/* Generated by tools/make_anchors.sh with BearSSL's brssl: the roots in tools/roots. */"
    echo '#include "okupa_tls.h"'
    "$tmp/brssl" ta "$tmp/roots.pem" | sed 's/^static const br_x509_trust_anchor TAs\[/const br_x509_trust_anchor ok_tls_anchors[/; s/^#define TAs_NUM .*//'
    echo "const size_t ok_tls_anchor_count = sizeof ok_tls_anchors / sizeof ok_tls_anchors[0];"
} > core/src/tls_anchors.c
rm -rf "$tmp"
