"""Writes game/src/friend_page.c from tools/friend/page.html: the page a
friend's browser loads, as C string pieces (C99 caps one literal at 4095
characters). Run after editing the page; `make friend-page-check` fails if
the two differ."""
import sys

SRC, OUT = "tools/friend/page.html", "game/src/friend_page.c"


def c_string(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def render(page):
    pieces, cut = [], 3000
    while page:
        piece = page[:cut]
        page = page[cut:]
        pieces.append(piece)
    lines = ["/* Generated by tools/friend/embed.py from tools/friend/page.html: do not edit. */",
             '#include "okupa_friend.h"', "", "const char *const ok_friend_page[] = {"]
    for p in pieces:
        lines.append("    " + c_string(p) + ",")
    lines += ["    0};", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    out = render(open(SRC, encoding="utf-8").read())
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        sys.exit(0 if open(OUT, encoding="utf-8").read() == out else "friend_page.c is out of date: python3 tools/friend/embed.py")
    open(OUT, "w", encoding="utf-8").write(out)
