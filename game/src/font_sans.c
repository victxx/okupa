const ok_font_sans ok_sans_bold = {13, 11, bold_adv, bold_rows[0]};
int ok_text_width(const ok_font_sans *f, const char *s)
{
    int w = 0;
    for (; *s; s++) {
        unsigned c = (unsigned char)*s;
        w += c >= 32 && c < 127 ? f->advance[c - 32] : f->advance[0];
    }
    return w;
}

void ok_text_draw(uint16_t *frame, const ok_font_sans *f, int x, int y, const char *s, uint16_t colour)
{
    for (; *s; s++) {
        unsigned c = (unsigned char)*s, r, b;
        if (c < 32 || c >= 127) c = '?';
        for (r = 0; r < f->height; r++) {
            uint16_t bits = f->rows[(c - 32) * f->height + r];
            int py = y + (int)r;
            if (!bits || py < 0 || py >= 192) continue;
            for (b = 0; b < 16; b++)
                if (bits >> b & 1 && x + (int)b >= 0 && x + (int)b < 256) frame[py * 256 + x + (int)b] = colour;
        }
        x += f->advance[c - 32];
    }
}
